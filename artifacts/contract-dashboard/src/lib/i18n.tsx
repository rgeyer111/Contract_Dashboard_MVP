export type MessageId = keyof typeof en;

type LanguageContextValue = { language: UiLanguage; setLanguage: (language: UiLanguage) => void; t: <K extends MessageId>(id: K, ...args: MessageArgs<K>) => string; };
const LanguageContext = createContext<LanguageContextValue | null>(null);
export function LanguageProvider({ children }: { children: ReactNode }) {
 const [language, setLanguageState] = useState<UiLanguage>(() => localStorage.getItem(LANGUAGE_STORAGE_KEY) === "de-CH" ? "de-CH" : "en");
 useEffect(() => { document.documentElement.lang = language; }, [language]);
 const setLanguage = (next: UiLanguage) => { localStorage.setItem(LANGUAGE_STORAGE_KEY, next); setLanguageState(next); };
 const t: LanguageContextValue["t"] = (id, ...args) => translate(language, id, ...args);
 return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>;
}
export function useLanguage() { const context = useContext(LanguageContext); if (!context) throw new Error("useLanguage must be used within LanguageProvider"); return context; }
export function LanguageSwitch() { const { language, setLanguage, t } = useLanguage(); return <select value={language} onChange={(event) => setLanguage(event.target.value as UiLanguage)} aria-label={t("ui.interface.language")} className="h-9 rounded-md border border-input bg-background px-2 text-xs font-bold outline-none focus:ring-2 focus:ring-primary/20"><option value="en">{t("ui.english")}</option><option value="de-CH">Deutsch (Schweiz)</option></select>; }

export function translate<K extends MessageId>(language: UiLanguage, id: K, ...args: MessageArgs<K>): string {
  const template = catalogs[language][id] as (...values: MessageArgs<K>) => string;
  return template(...args);
}

